package oo2.redictado.core;

import java.lang.reflect.Constructor;
import java.util.IdentityHashMap;
import java.util.Map;

import org.antlr.v4.runtime.CommonToken;
import org.antlr.v4.runtime.ParserRuleContext;
import org.antlr.v4.runtime.Token;
import org.antlr.v4.runtime.tree.ErrorNode;
import org.antlr.v4.runtime.tree.ErrorNodeImpl;
import org.antlr.v4.runtime.tree.ParseTree;
import org.antlr.v4.runtime.tree.TerminalNode;
import org.antlr.v4.runtime.tree.TerminalNodeImpl;

/**
 * Makes deep copies of a parse tree, so that a sniffer that modifies the tree
 * it receives does not affect the other sniffers.
 *
 * The copy shares nothing with the original: every node and every token is
 * new. Nodes keep their class (for example, the contexts ANTLR generates for
 * each rule), so the copy can be visited like the original. It works with
 * the trees of any grammar.
 */
public class TreeCopier {
    private final Map<Token, Token> tokens = new IdentityHashMap<>();

    /**
     * @param tree the parse tree to copy
     * @return a deep copy of the parse tree
     */
    @SuppressWarnings("unchecked")
    public static <T extends ParserRuleContext> T copy(T tree) {
        return (T) new TreeCopier().copyContext(tree, null);
    }

    private ParseTree copyNode(ParseTree node, ParserRuleContext parent) {
        if (node instanceof ErrorNode error) {
            return parent.addErrorNode(new ErrorNodeImpl(this.copyToken(error.getSymbol())));
        }
        if (node instanceof TerminalNode terminal) {
            return parent.addChild(new TerminalNodeImpl(this.copyToken(terminal.getSymbol())));
        }
        ParserRuleContext context = this.copyContext((ParserRuleContext) node, parent);
        parent.addAnyChild(context);
        return context;
    }

    private ParserRuleContext copyContext(ParserRuleContext original, ParserRuleContext parent) {
        ParserRuleContext copy = this.newContext(original, parent);
        if (original.children != null) {
            original.children.forEach(child -> this.copyNode(child, copy));
        }
        copy.start = this.copyToken(original.start);
        copy.stop = this.copyToken(original.stop);
        copy.exception = original.exception;
        return copy;
    }

    private ParserRuleContext newContext(ParserRuleContext original, ParserRuleContext parent) {
        try {
            // Every context generated by ANTLR has this constructor, as long as
            // the grammar doesn't use alternative labels (# label).
            Constructor<? extends ParserRuleContext> constructor =
                    original.getClass().getConstructor(ParserRuleContext.class, int.class);
            return constructor.newInstance(parent, original.invokingState);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("Cannot copy " + original.getClass().getSimpleName(), e);
        }
    }

    private Token copyToken(Token token) {
        if (token == null) {
            return null;
        }
        // The same token is shared by a terminal node and the start/stop of its
        // ancestors, so each token is copied only once.
        return this.tokens.computeIfAbsent(token, CommonToken::new);
    }
}
